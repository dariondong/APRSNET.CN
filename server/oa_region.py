def _width(pattern):
    """这个写法管几个字符：`JA-JS` 管两位，`AF0-AF9` 管三位，`B` 管一位。"""
    dash = pattern.find("-")
    return dash if dash > 0 else len(pattern)


_ORDERED = sorted(REGIONS, key=lambda item: -_width(item[0]))


def region_of(call):
    """呼号 → (中文名, 英文名)。认不出来就给 ("", "")。"""
    text = str(call or "").strip().upper()
    if "-" in text:
        head, _, ssid = text.rpartition("-")
        if ssid.isdigit() and head:
            text = head
    if not text:
        return ("", "")
    for pattern, zh, en in _ORDERED:
        dash = pattern.find("-")
        if dash > 0:
            lo, hi = pattern[:dash], pattern[dash + 1:]
            head = text[:len(lo)]
            if lo <= head <= hi:
                return (zh, en)
        elif text.startswith(pattern):
            return (zh, en)
    return ("", "")
